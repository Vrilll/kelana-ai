"""
KelanaAI - Retrieval check (no AWS required)
Session 9

Runs the five evaluation questions through the retriever only, and reports
whether the passage that actually contains the answer came back.

This is the half of RAG that can be verified offline: if retrieval does not
surface the right document, no amount of prompting will fix the answer.

    cd backend
    python scripts/check_retrieval.py
"""

import argparse
import sys
from datetime import date
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BACKEND_DIR))

from kb_questions import QUESTIONS  # noqa: E402
from services import kb_service  # noqa: E402
from services.fact_check import covers, normalise  # noqa: E402

def build_markdown(rows, corpus, documents, passed, failed, facts_missing, total_facts) -> str:
    """The same result as the console output, as a committable report."""
    lines = [
        "# Retrieval check",
        "",
        f"_Generated by `backend/scripts/check_retrieval.py` on {date.today().isoformat()}._",
        "",
        f"- Retrieval backend: `{kb_service.retrieval_backend()}`",
        f"- Corpus: {len(documents)} documents, {len(corpus)} chunks",
        f"- Passages per query: {kb_service.DEFAULT_TOP_K}",
        "",
        "This checks the half of RAG that needs no model call: given each question,",
        "does the retriever surface the passage that actually contains the answer?",
        "If it does not, no amount of prompting will fix the generated answer.",
        "",
        "## Summary",
        "",
        f"- **{passed}/{passed + failed}** questions retrieved their expected source document",
        f"- **{total_facts - facts_missing}/{total_facts}** expected facts are present in the retrieved context",
        "",
        "| Question | Expected document | Retrieved | Facts in context |",
        "|----------|-------------------|-----------|------------------|",
    ]

    for row in rows:
        lines.append(
            f"| {row['id']} | {', '.join(sorted(row['expected']))} | "
            f"{'yes' if row['hit'] else 'NO'} | {row['facts_found']}/{row['facts_total']} |"
        )

    lines += ["", "## Per question", ""]

    for row in rows:
        lines += [
            f"### {row['id']}. {row['question']}",
            "",
            "Top passages:",
            "",
        ]
        for rank, (score, source) in enumerate(row["passages"], start=1):
            lines.append(f"{rank}. `{source}` — score {score}")
        lines += [""]
        if row["missing_facts"]:
            lines += ["Facts not found in the retrieved context:", ""]
            lines += [f"- {f}" for f in row["missing_facts"]]
            lines += [""]

    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Check knowledge base retrieval")
    parser.add_argument("--out", help="also write a markdown report to this path")
    args = parser.parse_args()

    corpus = kb_service.load_corpus()
    documents = sorted({label.split(" > ")[0] for label, _ in corpus})

    print(f"backend : {kb_service.retrieval_backend()}")
    print(f"corpus  : {len(corpus)} chunks from {len(documents)} documents")
    for doc in documents:
        print(f"          - {doc}")

    passed = 0
    failed = 0
    facts_missing = 0
    rows = []

    for item in QUESTIONS:
        print(f"\n{'=' * 72}\n{item['id']}: {item['question']}")

        passages = kb_service.retrieve(item["question"])
        retrieved_docs = {p.source.split(" ")[0] for p in passages}
        expected_docs = set(item["source_docs"])

        print(f"\n  retrieved {len(passages)} passages:")
        for rank, passage in enumerate(passages, start=1):
            first_line = passage.text.strip().splitlines()[0][:70]
            print(f"    {rank}. score {passage.score:>7}  {passage.source}")
            print(f"       {first_line}")

        hit = bool(expected_docs & retrieved_docs)
        if hit:
            passed += 1
            print(f"\n  OK   expected {sorted(expected_docs)} -> found {sorted(retrieved_docs)}")
        else:
            failed += 1
            print(f"\n  MISS expected {sorted(expected_docs)} -> found {sorted(retrieved_docs)}")

        # Does the retrieved text actually contain the facts we need?
        joined = normalise(" ".join(p.text for p in passages))
        missing_facts = []
        for fact in item["expected_facts"]:
            covered, missing = covers(fact, joined)
            if covered:
                print(f"    [yes] {fact}")
            else:
                facts_missing += 1
                missing_facts.append(fact)
                print(f"    [NO ] {fact}   (missing: {', '.join(missing)})")

        rows.append(
            {
                "id": item["id"],
                "question": item["question"],
                "expected": expected_docs,
                "hit": hit,
                "passages": [(p.score, p.source) for p in passages],
                "facts_total": len(item["expected_facts"]),
                "facts_found": len(item["expected_facts"]) - len(missing_facts),
                "missing_facts": missing_facts,
            }
        )

    print(f"\n{'=' * 72}")
    total_facts = sum(len(q["expected_facts"]) for q in QUESTIONS)
    print(f"{passed} questions retrieved the right document, {failed} missed")
    print(
        f"{total_facts - facts_missing}/{total_facts} expected facts present "
        f"in the retrieved context"
    )
    if args.out:
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(
            build_markdown(
                rows, corpus, documents, passed, failed, facts_missing, total_facts
            ),
            encoding="utf-8",
        )
        print(f"Report written to {out}")

    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
