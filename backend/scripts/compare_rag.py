"""
KelanaAI - RAG vs base model comparison
Session 9

Asks the five evaluation questions twice: once grounded in the knowledge base,
once with no context at all. Scores both answers against the facts that a
correct answer must contain, and writes the result to docs/rag-vs-base-model.md.

    cd backend
    python scripts/compare_rag.py

Needs AWS credentials with bedrock:InvokeModel. Ten model calls in total.
Retrieval uses the Bedrock Knowledge Base when BEDROCK_KNOWLEDGE_BASE_ID is set,
otherwise the local BM25 retriever over the same documents.
"""

import argparse
import sys
from datetime import date
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BACKEND_DIR))

from botocore.exceptions import BotoCoreError, ClientError, NoCredentialsError  # noqa: E402

from kb_questions import QUESTIONS  # noqa: E402
from services import kb_service  # noqa: E402
from services.fact_check import score  # noqa: E402

REPORT = BACKEND_DIR.parent / "docs" / "rag-vs-base-model.md"

def main() -> int:
    parser = argparse.ArgumentParser(description="Compare RAG and base-model answers")
    parser.add_argument(
        "--questions", nargs="*", help="only run these ids, e.g. Q1 Q3"
    )
    args = parser.parse_args()

    selected = [
        q for q in QUESTIONS if not args.questions or q["id"] in args.questions
    ]

    backend = kb_service.retrieval_backend()
    corpus = kb_service.load_corpus()
    documents = sorted({label.split(" > ")[0] for label, _ in corpus})

    lines: list[str] = [
        "# RAG vs base model",
        "",
        f"_Generated by `backend/scripts/compare_rag.py` on {date.today().isoformat()}._",
        "",
        f"- Retrieval backend: `{backend}`",
        f"- Model: `{kb_service.BEDROCK_MODEL_ID}`",
        f"- Knowledge base: {len(documents)} documents, {len(corpus)} chunks",
        "",
        "Each question is asked twice with the same model and the same wording. The"
        " only difference is whether retrieved passages are supplied. Answers are"
        " scored against the facts a correct answer must contain.",
        "",
        "> **Read the answers, not just the scores.** Scoring is keyword coverage:"
        " a fact counts as present when every number in it appears and at least"
        " 70% of its other content words do. That under-credits a correct answer"
        " that paraphrases, and it cannot detect a fluent wrong answer at all."
        " See [rag-findings.md](rag-findings.md) for a read of what each answer"
        " actually got right.",
        "",
        "## Scoreboard",
        "",
        "| Question | RAG | Base model |",
        "|----------|-----|------------|",
    ]

    details: list[str] = []
    rag_total = base_total = possible = 0

    for item in selected:
        print(f"{item['id']} ...", flush=True)

        # temperature 0: this is an evaluation, so the same inputs should give
        # the same scores. At 0.2 the totals moved by several facts between
        # identical runs, which made the comparison impossible to cite.
        rag = kb_service.answer_with_rag(item["question"], temperature=0)
        base = kb_service.answer_with_base_model(item["question"], temperature=0)

        rag_hits, rag_missed = score(rag["answer"], item["expected_facts"])
        base_hits, base_missed = score(base["answer"], item["expected_facts"])
        total = len(item["expected_facts"])

        rag_total += rag_hits
        base_total += base_hits
        possible += total

        lines.append(
            f"| {item['id']} | {rag_hits}/{total} | {base_hits}/{total} |"
        )

        details += [
            "",
            f"### {item['id']}. {item['question']}",
            "",
            f"**Why this needs the knowledge base.** {item['why_rag_is_needed']}",
            "",
            f"**Retrieved passages ({len(rag['sources'])})**",
            "",
        ]
        for source in rag["sources"]:
            details.append(f"- `{source['source']}` (score {source['score']})")

        details += [
            "",
            f"**RAG answer — {rag_hits}/{total} facts**",
            "",
            "```",
            rag["answer"],
            "```",
            "",
            f"**Base-model answer — {base_hits}/{total} facts**",
            "",
            "```",
            base["answer"],
            "```",
            "",
            "**Facts each answer missed**",
            "",
            f"- RAG: {', '.join(rag_missed) if rag_missed else 'none'}",
            f"- Base model: {', '.join(base_missed) if base_missed else 'none'}",
        ]

    lines.append(f"| **Total** | **{rag_total}/{possible}** | **{base_total}/{possible}** |")
    lines += details
    lines.append("")

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines), encoding="utf-8")

    print(f"\nRAG {rag_total}/{possible}, base model {base_total}/{possible}")
    print(f"Written to {REPORT}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except NoCredentialsError:
        print(
            "No AWS credentials found. This script calls Bedrock, so it needs "
            "credentials with bedrock:InvokeModel.\n"
            "Retrieval alone can be checked without AWS: python scripts/check_retrieval.py"
        )
        raise SystemExit(1)
    except (ClientError, BotoCoreError) as error:
        print(f"AWS call failed: {error}")
        raise SystemExit(1)
