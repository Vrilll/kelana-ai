"""
KelanaAI - Database Connection
Session 4: Persistence Layer (PostgreSQL + SQLAlchemy)
"""

import os

from dotenv import load_dotenv
from sqlalchemy import create_engine, text
from sqlalchemy.orm import declarative_base, sessionmaker

# load .env so os.getenv() can read it
load_dotenv()

# connection string from .env - never hardcode secrets
DATABASE_URL = os.getenv("DATABASE_URL")

# engine = the connection pool
engine = create_engine(DATABASE_URL)

# SessionLocal = a factory for DB sessions
SessionLocal = sessionmaker(bind=engine, autoflush=False)

# Base = all ORM models inherit from this
Base = declarative_base()


def init_db() -> None:
    """Create all SQLAlchemy tables for the configured database."""
    Base.metadata.create_all(bind=engine)

    # create_all() only creates missing TABLES, it never adds a new column to a
    # table that already exists, so columns added in later sessions are patched
    # in here. "ADD COLUMN IF NOT EXISTS" is PostgreSQL syntax; on any other
    # backend a freshly created table already has every column, so skip it.
    if engine.dialect.name != "postgresql":
        return

    with engine.begin() as connection:
        # Session 5: itinerary generated by Amazon Bedrock
        connection.execute(
            text("ALTER TABLE trips ADD COLUMN IF NOT EXISTS ai_recommendation TEXT")
        )

        # Session 7: travel style ("Solo", "Couple", "Family"). Added without a
        # DEFAULT on purpose - older rows stay NULL rather than being backfilled
        # with a style nobody actually chose.
        connection.execute(
            text("ALTER TABLE trips ADD COLUMN IF NOT EXISTS travel_style VARCHAR")
        )

        # Session 8: owning account. Also NULL for older rows, which means they
        # belong to nobody and are filtered out of every user's trip list.
        connection.execute(
            text("ALTER TABLE trips ADD COLUMN IF NOT EXISTS user_id INTEGER")
        )
